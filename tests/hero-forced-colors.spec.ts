import { test, expect } from '@playwright/test'

test('forced colors keeps authentic project sources and native actions without decorative media', async ({ page }) => {
  await page.emulateMedia({ forcedColors: 'active', reducedMotion: 'no-preference' })
  const requests: string[] = []
  page.on('request', request => { if (/\.mp4(?:[?#]|$)|atelier-room|amber-architecture/.test(request.url())) requests.push(request.url()) })
  await page.goto('/')
  await page.locator('.state-opening').waitFor({ state: 'detached' })
  await expect(page.locator('.hero-ambient-film, .hero-film-toggle')).toHaveCount(0)
  await expect(page.locator('.opening-specimen-community img')).toBeVisible()
  await expect(page.locator('.opening-specimen-accuflow img')).toBeVisible()
  await expect(page.locator('h1')).toBeVisible()
  await expect(page.getByRole('button', { name: 'View Work', exact: true })).toBeVisible()
  await expect(page.locator('.opening-studio-link')).toHaveAttribute('href', '/studio')
  await expect(page.locator('main')).toHaveAttribute('data-scroll-engine', 'static')
  await expect(page.locator('.pin-spacer')).toHaveCount(0)
  expect(requests).toEqual([])
})

test('enabling forced colors flattens the staged opening while preserving its real project evidence', async ({ page }) => {
  await page.emulateMedia({ forcedColors: 'none', reducedMotion: 'no-preference' })
  await page.addInitScript(() => { Object.defineProperty(navigator, 'hardwareConcurrency', { value: 8 }); Object.defineProperty(navigator, 'deviceMemory', { value: 8 }) })
  await page.goto('/')
  await page.locator('.state-opening').waitFor({ state: 'detached' })
  await expect(page.locator('.pin-spacer')).toHaveCount(1)
  const sources = await page.locator('.opening-specimen img').evaluateAll(nodes => nodes.map(node => (node as HTMLImageElement).src))
  await page.emulateMedia({ forcedColors: 'active' })
  await expect(page.locator('main')).toHaveAttribute('data-scroll-engine', 'static')
  await expect(page.locator('.pin-spacer')).toHaveCount(0)
  expect(await page.locator('.opening-specimen img').evaluateAll(nodes => nodes.map(node => (node as HTMLImageElement).src))).toEqual(sources)
  for (const specimen of await page.locator('.opening-specimen').all()) expect(await specimen.evaluate(node => getComputedStyle(node).transform)).toBe('none')
  await expect(page.locator('.home-cirs-proof')).toBeVisible()
  await expect(page.locator('.scroll-opening')).not.toHaveAttribute('data-hero-film', 'active')
  await expect(page.locator('.hero-ambient-film, .hero-film-toggle')).toHaveCount(0)
})
