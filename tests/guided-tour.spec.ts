declare global { interface Window { __tourFooterDeparture?: number } }

for (const variant of [
  { width: 1440, height: 1000, motion: 'no-preference' as const, touch: false },
  { width: 390, height: 844, motion: 'reduce' as const, touch: true },
]) test.describe(`Studio tour return at ${variant.width}px`, () => {
  test.use({ viewport: { width: variant.width, height: variant.height },
    reducedMotion: variant.motion, isMobile: variant.touch, hasTouch: variant.touch })

  test('explicit case Back preserves the linked film, footer position and native tour launcher after a later image refresh', async ({ page }) => {
    await page.addInitScript(() => {
      Object.defineProperty(navigator, 'hardwareConcurrency', { value: 8 })
      Object.defineProperty(navigator, 'deviceMemory', { value: 8 })
    })
    await ready(page, '/studio#ted-ed-2026')
    const title = page.locator('.screening-title-card h3')
    await expect(title).toHaveText('TED-Ed auditions')
    const { tour, opener } = await openKeyboard(page)
    await expect(title).toHaveText('TED-Ed auditions')
    const explore = tour.locator('.tour-explore')
    await explore.focus()
    await explore.evaluate(node => node.addEventListener('click', () => {
      // Capture the actual departure before App removes the old scroll scene.
      window.__tourFooterDeparture = window.scrollY
    }, { capture: true, once: true }))
    await page.keyboard.press('Enter')
    const departureTop = await page.evaluate(() => window.__tourFooterDeparture!)
    expect(departureTop).toBeGreaterThan(500)
    await expect(page).toHaveURL(/\/projects\/cirs$/)
    await page.locator('.state-opening').waitFor({ state: 'detached' })
    await expect(page.locator('h1')).toBeFocused()
    await page.getByRole('button', { name: 'Back to portfolio', exact: true }).focus()
    await page.keyboard.press('Enter')
    await expect(page).toHaveURL(/\/studio#ted-ed-2026$/)
    await page.locator('.state-opening').waitFor({ state: 'detached' })
    await expect(title).toHaveText('TED-Ed auditions')
    await expect(opener).toBeFocused()
    await expect(opener).toBeInViewport()
    expect(await opener.getAttribute('tabindex')).toBeNull()
    await expect.poll(() => page.evaluate(top => Math.abs(scrollY - top), departureTop)).toBeLessThan(4)
    // A later layout refresh must not reinterpret the film hash as a fresh
    // request to jump from the saved footer back to the projection.
    await page.locator('.screening-still').evaluate(image => image.dispatchEvent(new Event('load')))
    await page.waitForTimeout(800)
    expect(await page.evaluate(top => Math.abs(scrollY - top), departureTop)).toBeLessThan(4)
    await expect(opener).toBeFocused()
    await expect(title).toHaveText('TED-Ed auditions')
    await expect(page).toHaveURL(/\/studio#ted-ed-2026$/)
  })
})
