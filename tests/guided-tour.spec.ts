import { test, expect, type Page } from '@playwright/test'

async function ready(page: Page, path = '/') {
  await page.goto(path)
  await page.evaluate(() => document.fonts.ready)
  await page.locator('.state-opening').waitFor({ state: 'detached' })
}
async function openKeyboard(page: Page) {
  const opener = page.getByRole('button', { name: 'Take the 60-second tour', exact: true })
  await opener.focus()
  await page.keyboard.press('Enter')
  const tour = page.locator('.tour-panel')
  await expect(tour).toBeVisible()
  await expect(tour.locator('h3')).toBeFocused()
  return { tour, opener }
}

test('keyboard entry follows native tour controls, explicit close and Escape restore the launcher without moving the page', async ({ page }) => {
  await ready(page)
  const { tour, opener } = await openKeyboard(page)
  const top = await page.evaluate(() => scrollY)
  await page.keyboard.press('Tab')
  await expect(tour.locator('.tour-explore')).toBeFocused()
  await tour.getByRole('button', { name: 'Exit guided tour', exact: true }).focus()
  await page.keyboard.press('Enter')
  await expect(tour).toHaveCount(0)
  await expect(opener).toBeFocused()
  expect(await page.evaluate(() => scrollY)).toBe(top)
  await page.keyboard.press('Enter')
  await page.keyboard.press('Escape')
  await expect(tour).toHaveCount(0)
  await expect(opener).toBeFocused()
  expect(await page.evaluate(() => scrollY)).toBe(top)
})

