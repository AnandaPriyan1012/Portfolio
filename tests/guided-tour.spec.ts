  expect(panel!.y).toBeGreaterThanOrEqual(0)
  expect(panel!.x + panel!.width).toBeLessThanOrEqual(width)
  expect(panel!.y + panel!.height).toBeLessThanOrEqual(844)
  await tour.getByRole('button', { name: 'Next tour chapter', exact: true }).click()
  await expect(image).toHaveAttribute('src', '/media/vallalar-language-en-desktop.webp')
  await tour.getByRole('button', { name: 'Next tour chapter', exact: true }).click()
  await expect(image).toHaveAttribute('src', '/media/atlas-accuflow-home-desktop.webp')
  await tour.getByRole('button', { name: 'Next tour chapter', exact: true }).click()
  await expect(image).toHaveAttribute('src', '/media/vantara-masquerade-poster.jpg')
