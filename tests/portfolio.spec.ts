test('AP OS windows drag and its conventional-view exit restores focus', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'AP OS', exact: true }).click()
  const os = page.getByRole('dialog', { name: 'AP OS', exact: true })
  const window = os.locator('[data-window="cirs"]')
  const before = await window.boundingBox()
  const title = await window.locator('.os-window-titlebar').boundingBox()
  await page.mouse.move(title!.x + 170, title!.y + 20)
  await page.mouse.down()
  await page.mouse.move(title!.x + 270, title!.y + 70, { steps: 8 })
  await page.mouse.up()
  const after = await window.boundingBox()
  expect(after!.x).toBeGreaterThan(before!.x + 50)
  expect(after!.y).toBeGreaterThan(before!.y + 20)
  await os.getByRole('button', { name: 'Open Community', exact: true }).click()
  await expect(os.locator('[data-window="community"]')).toContainText('Social Media & Technology Head')
  await os.getByRole('button', { name: /Conventional view/ }).click()
  await expect(os).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'AP OS', exact: true })).toBeFocused()
})

